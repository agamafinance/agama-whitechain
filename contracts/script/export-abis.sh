#!/usr/bin/env bash
# Writes the ABI of every contract the keeper and the app talk to into ../abi, one file each, as a TS const so
# viem infers every argument and return type from it.
set -euo pipefail
cd "$(dirname "$0")/.."
forge build >/dev/null
for c in AgUSD CrossChainAllocator AttestedMessenger TestUSDC AbfAssetIssuer AgamaL1Receiver; do
  f=$(find out -name "$c.json" -path "*/$c.sol/*" | head -1)
  { printf '// Generated by contracts/script/export-abis.sh from the forge build. Do not edit.\nexport const %sAbi = ' "$c"
    printf '%s as const;\n' "$(jq '.abi' "$f")"; } > "../abi/$c.ts"
done
{ echo '// Generated by contracts/script/export-abis.sh.'
  for c in AgUSD CrossChainAllocator AttestedMessenger TestUSDC AbfAssetIssuer AgamaL1Receiver; do
    echo "export { ${c}Abi } from './$c';"
  done; } > ../abi/index.ts
echo "abi/ written"
